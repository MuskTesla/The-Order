async function resize(condition) {
  const geometry = await application.evaluate(async ({ BrowserWindow }, requested) => {
    const win = BrowserWindow.getAllWindows()[0]
    if (win.isMaximized()) win.unmaximize(); if (win.isMinimized()) win.restore()
    win.setContentSize(requested.width, requested.height); win.webContents.setZoomFactor(requested.zoom)
    await new Promise(resolve => setTimeout(resolve, 100))
    return { requested, bounds: win.getBounds(), content: win.getContentBounds(), zoom: win.webContents.getZoomFactor() }
  }, condition)
  assert.ok(Math.abs(geometry.content.width - condition.width) < 3 && Math.abs(geometry.content.height - condition.height) < 3, 'Requested window size not reached')
  await page.waitForFunction(actual => Math.abs(innerWidth - actual.width / actual.zoom) < 3 && Math.abs(innerHeight - actual.height / actual.zoom) < 3, { ...geometry.content, zoom: condition.zoom })
  return geometry
}
