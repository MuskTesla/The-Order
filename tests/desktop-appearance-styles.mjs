async function ownWindowFrame(label) {
  const condition = { width: 1100, height: 700, zoom: 1 }
  await resize(condition)
  await application.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].center())
  await page.waitForTimeout(150)
  try {
    // Enumeration stays in the Electron process. Retain pixels only from the
    // source matching this isolated BrowserWindow, never other window titles.
    const result = await application.evaluate(async ({ BrowserWindow, desktopCapturer }) => {
      const win = BrowserWindow.getAllWindows()[0], id = win.getMediaSourceId()
      const sources = await desktopCapturer.getSources({ types: ['window'], thumbnailSize: { width: 1600, height: 1200 }, fetchWindowIcons: false })
      const own = sources.find(source => source.id === id)
      if (!own || own.thumbnail.isEmpty()) return { captured: false, reason: 'Isolated window source was unavailable or empty' }
      return { captured: true, png: own.thumbnail.toPNG().toString('base64'), size: own.thumbnail.getSize(), bounds: win.getBounds(), sourceMatchedOwnWindow: true }
    })
    if (!result.captured) { report.unverified.push(`Own window ${label}: ${result.reason}`); return }
    const bytes = Buffer.from(result.png, 'base64'), file = path.join(output, `${label}-own-window-frame.png`)
    await fs.writeFile(file, bytes); delete result.png
    report.screenshots.push({ file, label, requested: condition, method: 'desktopCapturer exact isolated BrowserWindow source; thumbnail resolution may differ from physical pixels; native caption coverage requires image inspection', ...result, sha256: hash(bytes) })
  } catch (error) { report.unverified.push(`Own window ${label}: ${error.message}`) }
}
