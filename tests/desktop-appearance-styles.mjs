async function opticalState() {
  return page.evaluate(() => ({
    definitions: document.querySelectorAll('[data-liquid-definitions]').length,
    filters: document.querySelectorAll('[data-liquid-definitions] filter').length,
    inlineCount: [...document.querySelectorAll('[style]')].filter(node => node.style.getPropertyValue('--liquid-optics').trim()).length,
    surfaces: [...document.querySelectorAll('[data-liquid-surface]')].map(node => {
      const id = node.getAttribute('data-liquid-surface'), filter = document.getElementById(id), image = filter?.querySelector('feImage'), bounds = node.getBoundingClientRect(), href = image?.getAttribute('href') ?? ''
      let mapSize = null
      if (href.startsWith('data:image/png;base64,')) {
        const bytes = Uint8Array.from(atob(href.split(',')[1].slice(0, 32)), char => char.charCodeAt(0)), data = new DataView(bytes.buffer)
        mapSize = { width: data.getUint32(16), height: data.getUint32(20) }
      }
      return { id, classes: node.className, inline: node.style.getPropertyValue('--liquid-optics'), backdropFilter: getComputedStyle(node).backdropFilter,
        rect: { width: Math.round(bounds.width), height: Math.round(bounds.height) }, layoutSize: { width: node.offsetWidth, height: node.offsetHeight }, filterSize: filter ? { width: Number(filter.getAttribute('width')), height: Number(filter.getAttribute('height')) } : null,
        mapSize, displacementPasses: filter?.querySelectorAll('feDisplacementMap').length ?? 0 }
    }),
    foregrounds: [...document.querySelectorAll('.cover-foreground,.detail-foreground,.preview-art')].map(node => ({ classes: node.className, filter: getComputedStyle(node).filter, backdropFilter: getComputedStyle(node).backdropFilter, opticalSurface: node.hasAttribute('data-liquid-surface'), inline: node.style.getPropertyValue('--liquid-optics') })),
  }))
}
function assertOpticalSurfaces(optics) {
  assert.equal(optics.definitions, 1, 'Glass must install one owned SVG definitions node')
  assert.ok(optics.surfaces.length > 0 && optics.surfaces.length <= 12, 'Glass optical surface bound violated')
  assert.equal(optics.filters, optics.surfaces.length); assert.equal(optics.inlineCount, optics.surfaces.length)
  for (const surface of optics.surfaces) {
    assert.ok(surface.inline.includes(surface.id), 'Surface does not reference its own SVG filter')
    assert.ok(surface.backdropFilter.includes(surface.id), 'SVG optical filter is not applied to the actual backdrop')
    assert.equal(surface.displacementPasses, 3, 'Expected three wavelength displacement passes')
    assert.deepEqual(surface.filterSize, surface.layoutSize, 'SVG filter geometry does not match live layout dimensions before transforms')
    assert.ok(surface.mapSize?.width > 0 && surface.mapSize.height > 0 && Math.max(surface.mapSize.width, surface.mapSize.height) <= 512 && surface.mapSize.width * surface.mapSize.height <= 65536, 'Displacement map exceeds bounded dimensions')
  }
  for (const foreground of optics.foregrounds) {
    assert.equal(foreground.filter, 'none', 'Foreground cover art must stay undistorted')
    assert.equal(foreground.backdropFilter, 'none'); assert.equal(foreground.opticalSurface, false); assert.equal(foreground.inline, '')
  }
}
